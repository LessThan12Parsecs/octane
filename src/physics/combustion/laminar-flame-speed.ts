/**
 * Laminar premixed-flame properties of fuel–air(–residual) mixtures: unstretched laminar
 * burning velocity S_L, flame thickness, density (expansion) ratio, Lewis numbers and the
 * burned-gas Markstein length. SI units (m, s, K, Pa, mol).
 *
 * ── Laminar burning velocity (default model) ───────────────────────────────────────────────
 *   S_L(fuel, φ, Tu, p, x) = [Σ_k τ_k S_L,k(φ, Tu, p)] · F_dil(x; φ, Tu, p) · G_lim(φ; Tu, x)
 *
 *  • S_L,k — pure-fuel burning velocity (unstretched, adiabatic, undiluted, standard air):
 *      CH4            tabulated FreeFlame solutions, GRI-Mech 3.0 (Smith et al. 1999)
 *      IC8H18, NC7H16 tabulated FreeFlame solutions, PRF_HT mechanism of Jerzembeck, Peters,
 *                     Pepiot-Desjardins & Pitsch, Combust. Flame 156 (2009) 292 (reduced from
 *                     the LLNL PRF mechanisms; validated by its authors at 1 atm and 10–25 bar)
 *      C3H8           Amirante, Distaso, Tamburrano & Reitz, Int. J. Engine Res. 18 (2017) 951,
 *                     Tables 6–7 (fit to measurements at 1–50 atm, 298–800 K; GRI-3.0 is not
 *                     used: it over-predicts measured propane S_L by 20–27 %, test file)
 *      C2H5OH         tabulated from the correlation of Vancoillie, Demuynck, Galle, Verhelst &
 *                     van Oijen, Fuel 102 (2012) 460, Eqs. 2–4 / Table 4 (fit to ~1500 flames of
 *                     the Li et al. 2007 ethanol mechanism at 400–900 K, 5–85 bar, φ 0.5–2;
 *                     below 5 bar continued as its local power law, see flamespeed_fit.py).
 *                     Gülder (1984) is NOT used: with β = −0.17 it predicts the same S_L at
 *                     373 K / 10 bar as at 300 K / 1 bar (0.44 vs 0.45 m/s, φ = 1), 45 % above
 *                     iso-octane; Vancoillie et al. §2.2 show the old correlations miss the
 *                     pressure dependence.
 *    The tables (tools/reference/flamespeed_*.py; Cantera 3.2 FreeFlame, mixture-averaged
 *    transport, grid-converged to ≲ 1 %) span φ 0.5–1.6 × Tu 300–900 K × p 1–60 bar and are
 *    interpolated with tensor-product cubic Hermite splines in (φ, ln Tu, ln p) on ln S_L (C¹);
 *    outside, ln S_L continues with its boundary gradient (local power law, C¹). This replaces
 *    power-law correlations, which the oracles show to be badly off at engine conditions (CH4 at
 *    800 K / 40 bar: Gülder 1984 −28 %, Amirante 2017 −47 % vs GRI-3.0; the interaction of φ, Tu
 *    and p is strong — cf. Vancoillie et al., Fuel 102 (2012) 460, §3.1). The published
 *    correlations remain available (laminarFlameSpeedModel, metghalchiKeck1982, gulder1984,
 *    amirante2017, rhodesKeck1985Indolene).
 *  • τ_k — energy-fraction blending rule: τ_k = x_k Q_k / Σ x_j Q_j (x fuel mole fractions, Q
 *    molar lower heating values); Sileghem et al., Fuel 112 (2013) 355 (iso-octane/n-heptane/
 *    toluene; energy-fraction rule "accurate enough" for the blends' measured S_L), after
 *    Sileghem et al., Energy Fuels 26 (2012) 4721. Reproduces PRF_HT flames of iso-octane/
 *    n-heptane blends (test file).
 *  • F_dil — residual/EGR (complete-combustion products of the same mixture, MASS fraction x):
 *    thermal theory (Zel'dovich–Frank-Kamenetskii) F = exp[−E_a/(2R) (1/T_ad(x) − 1/T_ad(0))]
 *    with the HP-equilibrium T_ad from generated tables (x = 0, 0.15, 0.3; quadratic in x) and
 *    an effective E_a(φ, p, x) tabulated from paired diluted/undiluted detailed-chemistry flames
 *    (ACTIVATION_ENERGY_TABLE; flamespeed_dilution.py). The classical fixed factor
 *    F = 1 − 2.06 f^0.773 (Rhodes & Keck, SAE 850047, 1985, Eq. 25, a = 2.06, b = 0.773; f = VOLUME
 *    fraction of a 20 % CO2 / 80 % N2 simulated residual, 350–550 K) is kept as
 *    rhodesKeckDilutionFactor: it over-penalises heavier fuels, hot and off-stoichiometric
 *    mixtures (iso-octane, 700 K / 20 bar, x = 0.3: Cantera 0.29, Rhodes–Keck 0.19).
 *  • G_lim — smooth (C¹) cut-off to zero at the flammability limits (see flammabilityLimits):
 *    S_L ≡ 0 outside; a smoothstep over 5 % of the limit φ inside. Real limit flames have
 *    finite speeds (heat loss, buoyancy); the cut-off is the propagate/no-propagate switch.
 *  Implementation: per blend (cached by fuel composition) the node values of ln(Σ τ_k S_L,k) + ln F_dil
 *  at x = 0, 0.15, 0.3 are precomputed; per φ the φ-axis is contracted once; a call then costs two
 *  1-D Hermite weight sets, a 16-node sum, a quadratic in x and one exp.
 *
 * ── Other properties ─────────────────────────────────────────────────────────────────────
 *  • flameThickness — diffusive δ_D = α_u/S_L (Zel'dovich) and Blint's δ_B = 2 δ_D (T_b/T_u)^0.7
 *    (R.J. Blint, Combust. Sci. Technol. 49 (1986) 79; as quoted by Vancoillie et al. 2012,
 *    Eq. 10). α_u from thermo/transport.
 *  • burnedGasState — T_b from the equilibrium T_ad tables (default), from complete combustion
 *    (upper bound), or from an HP equilibrium solver; σ = ρ_u/ρ_b = n_b T_b/T_u.
 *  • lewisNumbers — α_u/D_k,m with Chapman–Enskog binary diffusivities (Hirschfelder, Curtiss &
 *    Bird 1954; Neufeld et al. 1972 Ω(1,1)*) and the mixture-averaged D_k,m = (1 − Y_k) /
 *    Σ_{j≠k} X_j/D_kj (Cantera's mixture-averaged model).
 *  • marksteinLength — hydrodynamic theory of Bechtold & Matalon, Combust. Flame 127 (2001) 1906,
 *    with λ ∝ ρD ∝ T^0.7 and the effective Lewis number of Addabbo, Bechtold & Matalon (2002),
 *    formulas as given by M. Matalon, CEFRC Summer School 2011, Lecture 8, slides 11–15.
 *
 * Hot path (laminarFlameSpeed) allocates nothing after the first call per blend: module-level
 * scratch, not re-entrant (single worker thread).
 */
