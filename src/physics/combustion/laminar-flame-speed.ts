/**
 * Closed-form (published-correlation) burning velocity of pure fuel `f` (FUEL_SPECIES position)
 * for fuels without a table, m/s: C3H8 — Amirante et al. (2017). CH4 / iso-octane / n-heptane /
 * ethanol fall back to Amirante (CH4), Metghalchi–Keck (1982) isooctane and Gülder (1984) ethanol
 * only if their tables are absent.
 */
function pureClosedForm(f: number, phi: number, Tu: number, p: number): number {
  switch (f) {
    case F_C3H8:
      return amirante2017(AMIRANTE_2017.C3H8, phi, Tu, p);
    case F_C2H5OH:
      return gulder1984(GULDER_1984.C2H5OH, phi, Tu, p);
    case F_CH4:
      return amirante2017(AMIRANTE_2017.CH4, phi, Tu, p);
    default:
      return metghalchiKeck1982(METGHALCHI_KECK_1982.isooctane, phi, Tu, p);
  }
}

/**
 * Undiluted, unstretched laminar burning velocity of pure fuel `f` WITHOUT the flammability
 * cut-off, m/s. Table fuels use the weights set by setTableWeights.
 */
function pureSL(f: number, phi: number, Tu: number, p: number): number {
  const tab = TABLE_BY_FUEL[f];
  if (tab !== null) return Math.exp(tableLnSL(tab));
  return pureClosedForm(f, phi, Tu, p);
}

