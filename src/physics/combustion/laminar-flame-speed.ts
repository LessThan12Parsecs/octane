/** One interpolation axis: nodes and the 3-point node-derivative stencils. */
interface Axis {
  n: number;
  x: Float64Array;
  /** Node derivative m_j = Σ_q D[3j+q] f[s_j + q]. */
  D: Float64Array;
  s: Int32Array;
}

function makeAxis(nodes: readonly number[]): Axis {
  const n = nodes.length;
  if (n < 4) throw new Error('interpolation axis needs ≥ 4 nodes');
  const x = Float64Array.from(nodes);
  const D = new Float64Array(3 * n);
  const s = new Int32Array(n);
  for (let j = 0; j < n; j++) {
    if (j === 0) {
      const h1 = x[1] - x[0];
      const h2 = x[2] - x[1];
      s[j] = 0;
      D[0] = -(2 * h1 + h2) / (h1 * (h1 + h2));
      D[1] = (h1 + h2) / (h1 * h2);
      D[2] = -h1 / (h2 * (h1 + h2));
    } else if (j === n - 1) {
      const h1 = x[n - 1] - x[n - 2];
      const h2 = x[n - 2] - x[n - 3];
      s[j] = n - 3;
      D[3 * j] = h1 / (h2 * (h1 + h2));
      D[3 * j + 1] = -(h1 + h2) / (h1 * h2);
      D[3 * j + 2] = (2 * h1 + h2) / (h1 * (h1 + h2));
    } else {
      const hl = x[j] - x[j - 1];
      const hr = x[j + 1] - x[j];
      s[j] = j - 1;
      D[3 * j] = -hr / (hl * (hl + hr));
      D[3 * j + 1] = (hr - hl) / (hl * hr);
      D[3 * j + 2] = hl / (hr * (hl + hr));
    }
  }
  return { n, x, D, s };
}

/**
 * Cubic-Hermite (finite-difference slopes) interpolation weights on a 4-node window: the
 * interpolant is Σ_q w[q] f[b + q] with b the returned window start. Outside the node range
 * the first-order Taylor expansion at the end node is used (C¹, linear extrapolation).
 */
function hermiteWeights(ax: Axis, xv: number, w: Float64Array): number {
  const { n, x, D, s } = ax;
  w[0] = 0;
  w[1] = 0;
  w[2] = 0;
  w[3] = 0;
  if (xv <= x[0]) {
    const dx = xv - x[0];
    w[0] = 1 + dx * D[0];
    w[1] = dx * D[1];
    w[2] = dx * D[2];
    return 0;
  }
  if (xv >= x[n - 1]) {
    const b = n - 4;
    const dx = xv - x[n - 1];
    const j = n - 1;
    w[3] = 1;
    const o = s[j] - b;
    w[o] += dx * D[3 * j];
    w[o + 1] += dx * D[3 * j + 1];
    w[o + 2] += dx * D[3 * j + 2];
    return b;
  }
  let i = 0;
  while (i < n - 2 && xv > x[i + 1]) i++;
  const b = i - 1 < 0 ? 0 : i - 1 > n - 4 ? n - 4 : i - 1;
  const h = x[i + 1] - x[i];
  const t = (xv - x[i]) / h;
  const t2 = t * t;
  const t3 = t2 * t;
  const h00 = 2 * t3 - 3 * t2 + 1;
  const h01 = -2 * t3 + 3 * t2;
  const h10 = (t3 - 2 * t2 + t) * h;
  const h11 = (t3 - t2) * h;
  w[i - b] += h00;
  w[i + 1 - b] += h01;
  let o = s[i] - b;
  w[o] += h10 * D[3 * i];
  w[o + 1] += h10 * D[3 * i + 1];
  w[o + 2] += h10 * D[3 * i + 2];
  o = s[i + 1] - b;
  w[o] += h11 * D[3 * i + 3];
  w[o + 1] += h11 * D[3 * i + 4];
  w[o + 2] += h11 * D[3 * i + 5];
  return b;
}

