const EA_NPHI = EA_PHI.length;
const EA_NP = EA_P.length;
const EA_LNP = Float64Array.from(EA_P, Math.log);

/**
 * Effective activation energy (J/mol) of pure fuel f (FUEL_SPECIES position) at equivalence ratio
 * φ and pressure p (Pa), for the diluted node ix (0: x = TABLE_XDIL[1], 1: x = TABLE_XDIL[2]):
 * bilinear in (φ, ln p) on ACTIVATION_ENERGY_TABLE, clamped to the table range (constant beyond).
 */
export function activationEnergy(f: number, phi: number, p: number, ix = 0): number {
  const t = ACTIVATION_ENERGY_TABLE[f];
  let i = 0;
  while (i < EA_NPHI - 2 && phi > EA_PHI[i + 1]) i++;
  let u = (phi - EA_PHI[i]) / (EA_PHI[i + 1] - EA_PHI[i]);
  u = u > 0 ? (u < 1 ? u : 1) : 0;
  const lp = Math.log(p);
  let k = 0;
  while (k < EA_NP - 2 && lp > EA_LNP[k + 1]) k++;
  let v = (lp - EA_LNP[k]) / (EA_LNP[k + 1] - EA_LNP[k]);
  v = v > 0 ? (v < 1 ? v : 1) : 0;
  const o = (ix * EA_NPHI + i) * EA_NP + k;
  return (
    (1 - u) * ((1 - v) * t[o] + v * t[o + 1]) + u * ((1 - v) * t[o + EA_NP] + v * t[o + EA_NP + 1])
  );
}

/** Exponent of the transport-property temperature dependence λ ∝ ρD ∝ T^a (Matalon 2011: "typically α = 0.7"). */
export const MARKSTEIN_TRANSPORT_EXPONENT = 0.7;

/**
 * n-point Gauss–Legendre nodes/weights mapped to [0, 1], computed by Newton iteration on
 * P_n (Golub–Welsch-free textbook construction; exact to round-off).
 */
function gaussLegendre01(n: number): [Float64Array, Float64Array] {
  const x = new Float64Array(n);
  const w = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    let t = Math.cos((Math.PI * (i + 0.75)) / (n + 0.5));
    let dp = 0;
    for (let it = 0; it < 100; it++) {
      let p0 = 1;
      let p1 = t;
      for (let k = 2; k <= n; k++) {
        const p2 = ((2 * k - 1) * t * p1 - (k - 1) * p0) / k;
        p0 = p1;
        p1 = p2;
      }
      dp = (n * (t * p1 - p0)) / (t * t - 1);
      const dt = p1 / dp;
      t -= dt;
      if (Math.abs(dt) < 1e-15) break;
    }
    x[i] = 0.5 * (1 - t);
    w[i] = 1 / ((1 - t * t) * dp * dp);
  }
  return [x, w];
}
const [GL16_X, GL16_W] = gaussLegendre01(16);

/**
 * The two integrals of the Bechtold–Matalon Markstein length for λ(x) = x^a (x = T/T_u):
 *   J1 = ∫_1^σ λ(x)/x dx = (σ^a − 1)/a,
 *   J2 = ∫_1^σ ln((σ−1)/(x−1)) λ(x)/x dx = (σ−1) ∫_0^1 (−ln s) (1 + (σ−1)s)^(a−1) ds,
 * the latter by 16-point Gauss–Legendre after s = v² (integrand −4 v ln v g(v²), regular).
 * Returns J1 in the first slot and J2 in the second of `out`.
 */
export function marksteinIntegrals(sigma: number, a: number, out: Float64Array = new Float64Array(2)): Float64Array {
  out[0] = a === 0 ? Math.log(sigma) : (Math.pow(sigma, a) - 1) / a;
  const sm1 = sigma - 1;
  let acc = 0;
  for (let q = 0; q < 16; q++) {
    const v = GL16_X[q];
    const s = v * v;
    acc += GL16_W[q] * (-4 * v * Math.log(v)) * Math.pow(1 + sm1 * s, a - 1);
  }
  out[1] = sm1 * acc;
  return out;
}

/** Markstein-length details. */
export interface MarksteinResult {
  /**
   * Burned-gas Markstein length, m, in the spherical-flame convention S_b = S_b0 − L_b κ
   * (Clavin 1985; Bradley et al. 1998; Jerzembeck et al. 2009, eq. 2), S_b0 = σ S_L.
   */
  burned: number;
  /** Markstein length relative to the unburned gas (S_n = S_L − L κ), m. */
  unburned: number;
  /** Burned-gas Markstein number L_b/l_f. */
  numberBurned: number;
  /** Flame length l_f = α_u/S_L, m. */
  lf: number;
  /** Density ratio used. */
  sigma: number;
  /** Zeldovich number β. */
  beta: number;
  /** Effective Lewis number. */
  leEff: number;
  /** Laminar burning velocity used, m/s. */
  SL: number;
}

const leScratch: LewisNumbers = { fuel: 0, oxygen: 0, deficient: 0, alphaU: 0 };
const mkInt = new Float64Array(2);

/**
 * Effective Lewis number (Addabbo, Bechtold & Matalon 2002, as in Matalon 2011 slide 12):
 * lean: [Le_O + (1 + φ̃) Le_F]/(2 + φ̃), φ̃ = β(1/φ − 1); rich: [Le_F + (1 + φ̃) Le_O]/(2 + φ̃),
 * φ̃ = β(φ − 1). → (Le_F + Le_O)/2 at φ = 1, the deficient reactant's Le far from it.
 */
export function effectiveLewisNumber(leF: number, leO: number, phi: number, beta: number): number {
  if (phi <= 1) {
    const pt = beta * (1 / phi - 1);
    return (leO + (1 + pt) * leF) / (2 + pt);
  }
  const pt = beta * (phi - 1);
  return (leF + (1 + pt) * leO) / (2 + pt);
}

/**
 * Burned-gas Markstein length (m), spherical-flame convention S_b = σS_L − L_b κ, from the
 * Bechtold & Matalon (2001) theory with λ ∝ T^0.7 (Matalon 2011, slide 15):
 *   L_b,BM / l_f = J1/(σ−1) + β(Le_eff − 1) J2 / (2(σ−1)),  L_b = σ L_b,BM
 * (BM define S_b = σS_L − σ L_b,BM K), unburned: L/l_f = σ J1/(σ−1) + β(Le_eff−1) J2/(2(σ−1)).
 * Inputs: S_L from laminarFlameSpeed, σ and T_b from burnedGasState (or `Tb`), Le from
 * lewisNumbers, β from activationEnergy. Theory note (Matalon): measured Markstein numbers
 * depend on the reference surface and are usually smaller than the asymptotic values.
 * Not a hot path (≈ 10 µs).
 */
export function marksteinLengths(
  fuel: FuelBlend,
  phi: number,
  Tu: number,
  p: number,
  xDiluent = 0,
  Tb?: number,
  out: MarksteinResult = { burned: 0, unburned: 0, numberBurned: 0, lf: 0, sigma: 0, beta: 0, leEff: 0, SL: 0 },
): MarksteinResult {
  const SL = laminarFlameSpeed(fuel, phi, Tu, p, xDiluent);
  const bg = burnedGasState(fuel, phi, Tu, p, xDiluent, 'table', bgScratch);
  let tb = bg.Tb;
  let sigma = bg.sigma;
  if (Tb !== undefined && Tb > Tu) {
    sigma *= Tb / tb;
    tb = Tb;
  }
  const le = lewisNumbers(fuel, phi, Tu, p, xDiluent, leScratch);
  let ea = 0;
  let ys = 0;
  for (let f = 0; f < NF; f++) {
    const y = fuel.X[FUEL_IDX[f]];
    if (!(y > 0)) continue;
    ea += y * activationEnergy(f, phi, p, 0);
    ys += y;
  }
  ea /= ys;
  const beta = (ea * (tb - Tu)) / (R_UNIVERSAL * tb * tb);
  const leEff = effectiveLewisNumber(le.fuel, le.oxygen, phi, beta);
  marksteinIntegrals(sigma, MARKSTEIN_TRANSPORT_EXPONENT, mkInt);
  const sm1 = sigma - 1;
  const lf = SL > 0 ? le.alphaU / SL : NaN; // non-propagating mixture → NaN lengths
  const second = (beta * (leEff - 1) * mkInt[1]) / (2 * sm1);
  const mb = mkInt[0] / sm1 + second;
  out.numberBurned = sigma * mb;
  out.burned = sigma * mb * lf;
  out.unburned = ((sigma * mkInt[0]) / sm1 + second) * lf;
  out.lf = lf;
  out.sigma = sigma;
  out.beta = beta;
  out.leEff = leEff;
  out.SL = SL;
  return out;
}

/**
 * Burned-gas Markstein length L_b (m) in the spherical-flame convention S_b = σ S_L − L_b κ
 * (see marksteinLengths). NaN outside the flammability limits (S_L = 0).
 * NOTE: ignition/kernel.ts (KernelGasState.marksteinLength) expects the UNBURNED-gas length
 * (S_n = S_L − L κ) — pass marksteinLengths(...).unburned there; L_b ≈ σ·L for heavy fuels.
 */
export function marksteinLength(fuel: FuelBlend, phi: number, Tu: number, p: number, xDiluent = 0): number {
  return marksteinLengths(fuel, phi, Tu, p, xDiluent).burned;
}
