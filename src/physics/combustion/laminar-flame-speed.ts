/**
 * Lower / upper flammability limits in air at 25 °C, 1 atm, volume % (upward propagation):
 * Zabetakis, USBM Bulletin 627 (1965), as commonly reproduced: CH4 5.0/15.0, C3H8 2.1/9.5,
 * n-C7H16 1.05/6.7, iso-C8H18 0.95/6.0, C2H5OH 3.3/19.
 * UNVERIFIED: the bulletin itself could not be fetched; secondary sources differ (e.g. CH4
 * 4.4/16.4 in EN 1839-type data, 5/15.8 in a 120-L sphere — Zlochower 2012; iso-octane UFL
 * 5.94). The limits only place the propagation cut-off, where S_L is already small.
 */
export const FLAMMABILITY_LIMITS_VOL = {
  lower: Float64Array.from([0.95, 1.05, 5.0, 2.1, 3.3]),
  upper: Float64Array.from([6.0, 6.7, 15.0, 9.5, 19.0]),
} as const;

/**
 * Temperature dependence of the limits, Zabetakis (1965) as quoted by Zlochower,
 * J. Loss Prev. Process Ind. 25 (2012) 555, Eqs. (1)–(2):
 *   L_t / L_25 = 1 − 7.84e−4 (t − 25 °C),   U_t / U_25 = 1 + 7.21e−4 (t − 25 °C).
 */
const LFL_TCOEF = 7.84e-4;
const UFL_TCOEF = 7.21e-4;
/** Relative width of the smooth cut-off band inside each limit (numerical device). */
const LIMIT_BAND = 0.05;

/** Output of flammabilityLimits. */
export interface FlammabilityLimits {
  /** Lean limit, equivalence ratio. */
  lean: number;
  /** Rich limit, equivalence ratio. */
  rich: number;
}

// [0] lean limit, [1] rich limit, [2] concentration → φ factor k (typed array: module-level `let`
// doubles are boxed on every write — hot paths must not allocate)
const LIM = Float64Array.of(0, 0, 1);

/**
 * Flammability limits in φ of the blend at 298.15 K without diluent, written to LIM[0]/LIM[1]
 * (and the concentration → φ factor k = ν/x_O2,air to LIM[2]: φ = k c/(1 − c)).
 * Blend: Le Chatelier's rule 1/L = Σ y_k/L_k on the fuel mole fractions y (Le Chatelier 1891;
 * Coward & Jones, USBM Bulletin 503, 1952); vol-% → φ with the dry-air O2 fraction.
 */
function baseLimits(fuel: FuelBlend): void {
  let invL = 0;
  let invU = 0;
  let nu = 0;
  let ysum = 0;
  const X = fuel.X;
  for (let f = 0; f < NF; f++) {
    const y = X[FUEL_IDX[f]];
    if (!(y > 0)) continue;
    invL += y / FLAMMABILITY_LIMITS_VOL.lower[f];
    invU += y / FLAMMABILITY_LIMITS_VOL.upper[f];
    nu += y * FUEL_NU_O2[f];
    ysum += y;
  }
  if (!(ysum > 0)) {
    LIM[0] = Infinity;
    LIM[1] = -Infinity;
    return;
  }
  const k = nu / ysum / AIR_X[SP.O2];
  const lfl = (0.01 * ysum) / invL;
  const ufl = (0.01 * ysum) / invU;
  LIM[0] = (lfl / (1 - lfl)) * k;
  LIM[1] = (ufl / (1 - ufl)) * k;
  LIM[2] = k;
}

/**
 * Flammability limits in φ at Tu (K) and diluent mass fraction x from the 298 K limits.
 * Temperature: Zabetakis (1965) linear laws on the limit concentrations (converted to φ).
 * Dilution: φ_lean/(1 − x) and φ_rich (1 − x) — the constant-limit-flame-temperature estimate
 * (heat release per unit mixture mass ∝ 1 − x); a model assumption, not a fitted law.
 */
function adjustLimits(lean298: number, rich298: number, k: number, Tu: number, x: number): void {
  const dt = Tu - 298.15;
  // φ = k c/(1 − c) with c the limit concentration: the Zabetakis laws scale c, not φ
  const cl = lean298 / (lean298 + k);
  const cu = rich298 / (rich298 + k);
  const l = cl * Math.max(1 - LFL_TCOEF * dt, 0.02);
  const u = Math.min(cu * (1 + UFL_TCOEF * dt), 0.95);
  const xd = x > 0 ? (x < 0.95 ? x : 0.95) : 0;
  LIM[0] = ((l / (1 - l)) * k) / (1 - xd);
  LIM[1] = (u / (1 - u)) * k * (1 - xd);
}

function computeLimits(fuel: FuelBlend, Tu: number, x: number): void {
  baseLimits(fuel);
  adjustLimits(LIM[0], LIM[1], LIM[2], Tu, x);
}

/** Flammability limits (equivalence ratios) of the blend at Tu (K), diluent mass fraction x. */
export function flammabilityLimits(
  fuel: FuelBlend,
  Tu: number,
  xDiluent = 0,
  out: FlammabilityLimits = { lean: 0, rich: 0 },
): FlammabilityLimits {
  computeLimits(fuel, Tu, xDiluent);
  out.lean = LIM[0];
  out.rich = LIM[1];
  return out;
}

function smoothstep(u: number): number {
  if (u <= 0) return 0;
  if (u >= 1) return 1;
  return u * u * (3 - 2 * u);
}

