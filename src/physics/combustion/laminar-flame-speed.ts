/**
 * Metghalchi & Keck, Combust. Flame 48 (1982) 191, Eqs. (16)–(18), (24) and Table 3A:
 *   S_u = S_u0 (Tu/298 K)^α (p/1 atm)^β,  S_u0 = B_m + B_2 (φ − φ_m)²,
 *   α = 2.18 − 0.8(φ − 1),  β = −0.16 + 0.22(φ − 1).
 * Table 3A (φ_m, B_m [cm/s], B_2 [cm/s]) verified against the paper (OCR of the 1982 scan):
 * methanol 1.11, 36.92, −140.51; propane 1.08, 34.22, −138.65 (from Metghalchi & Keck 1980);
 * isooctane 1.13, 26.32, −84.72; RMFD-303 (indolene) 1.13, 27.58, −78.34.
 * Stated accuracy ±10 % for 350–700 K and 1–50 atm, φ 0.8–1.5; "at room temperature the fit is
 * not as good" (Table 3B gives separate 298 K constants). Negative S_u0 (φ outside ≈0.57–1.69)
 * is clipped to 0.
 */
export const METGHALCHI_KECK_1982 = {
  methanol: { phiM: 1.11, Bm: 0.3692, B2: -1.4051 },
  propane: { phiM: 1.08, Bm: 0.3422, B2: -1.3865 },
  isooctane: { phiM: 1.13, Bm: 0.2632, B2: -0.8472 },
  indolene: { phiM: 1.13, Bm: 0.2758, B2: -0.7834 },
} as const;

/** Metghalchi & Keck (1982) burning velocity, m/s (see METGHALCHI_KECK_1982). */
export function metghalchiKeck1982(
  c: { phiM: number; Bm: number; B2: number },
  phi: number,
  Tu: number,
  p: number,
): number {
  const d = phi - c.phiM;
  const s0 = c.Bm + c.B2 * d * d;
  if (!(s0 > 0)) return 0;
  const alpha = 2.18 - 0.8 * (phi - 1);
  const beta = -0.16 + 0.22 * (phi - 1);
  return s0 * Math.pow(Tu / 298, alpha) * Math.pow(p / P_ATM, beta);
}

/**
 * Gülder (1984, SAE 841000; 1982 Proc. Combust. Inst. 19:275) exponential form:
 *   S_L = W φ^η exp(−ξ(φ − 1.075)²) (Tu/T0)^α (p/p0)^β.
 * CH4 and C3H8 constants as reproduced in Amirante et al. (2017) Table 3 and text
 * (W = 42.2 / 44.6 cm/s, η = 0.15 / 0.12, ξ = 5.18 / 4.95, α = 2 / 1.77, β = −0.5 / −0.2).
 * Iso-octane and ethanol: W and η are consistent with the φ = 1.075 maxima quoted from
 * Gülder (1982) (isooctane 0.455 m/s, ethanol 0.47 m/s), and β = −0.22 / −0.17 match the
 * stoichiometric pressure exponents quoted from the same abstract.
 * UNVERIFIED: ξ (4.48 isooctane, 6.34 ethanol), α (1.56 isooctane, 1.75 ethanol — the latter
 * only via a secondary quotation), and the reference state T0 = 300 K, p0 = 1 bar (Gülder:
 * "0.1–0.8 MPa, 300–500 K" range).
 * Comparison only — not used by the default model (its constant β = −0.17 for ethanol gives
 * S_L(373 K, 10 bar) ≈ S_L(300 K, 1 bar); ethanol now uses Vancoillie et al. 2012).
 */
export const GULDER_1984 = {
  CH4: { W: 0.422, eta: 0.15, xi: 5.18, alpha: 2.0, beta: -0.5 },
  C3H8: { W: 0.446, eta: 0.12, xi: 4.95, alpha: 1.77, beta: -0.2 },
  IC8H18: { W: 0.4658, eta: -0.326, xi: 4.48, alpha: 1.56, beta: -0.22 },
  C2H5OH: { W: 0.465, eta: 0.25, xi: 6.34, alpha: 1.75, beta: -0.17 },
} as const;

/** Gülder (1984) burning velocity, m/s (see GULDER_1984). */
export function gulder1984(
  c: { W: number; eta: number; xi: number; alpha: number; beta: number },
  phi: number,
  Tu: number,
  p: number,
): number {
  if (!(phi > 0)) return 0;
  const d = phi - 1.075;
  return c.W * Math.pow(phi, c.eta) * Math.exp(-c.xi * d * d) * Math.pow(Tu / 300, c.alpha) * Math.pow(p / 1e5, c.beta);
}

/**
 * Amirante, Distaso, Tamburrano & Reitz, Int. J. Engine Res. 18 (2017) 951 (pre-print,
 * Politecnico di Bari repository), Eqs. (1), (10), (16) with Tables 6–7:
 *   S_L = W φ^η exp(−ξ(φ − φ0)²) (Tu/298 K)^α (p/1 atm)^β,
 *   α = a1 φ² − a2 φ + a3,  β = −b1 φ² + b2 φ − b3.
 * Fitted to measurements over φ 0.6–1.7, 1–50 atm, 298–800 K.
 */
export const AMIRANTE_2017 = {
  CH4: { W: 0.3885, eta: -0.2, xi: 6.45, phi0: 1.08, a: [4.9199, 10.287, 6.9258], b: [1.3712, 2.6808, 1.7492] },
  C3H8: { W: 0.4211, eta: -0.25, xi: 5.24, phi0: 1.1, a: [2.762, 5.8808, 4.9221], b: [0.925, 2.0, 1.356] },
  gasoline: { W: 0.3682, eta: -0.22, xi: 4.86, phi0: 1.11, a: [3.28, 7.52, 5.93], b: [0.925, 2.012, 1.365] },
} as const;

/** Amirante et al. (2017) burning velocity, m/s (see AMIRANTE_2017). */
export function amirante2017(
  c: { W: number; eta: number; xi: number; phi0: number; a: readonly number[]; b: readonly number[] },
  phi: number,
  Tu: number,
  p: number,
): number {
  if (!(phi > 0)) return 0;
  const d = phi - c.phi0;
  const alpha = c.a[0] * phi * phi - c.a[1] * phi + c.a[2];
  const beta = -c.b[0] * phi * phi + c.b[1] * phi - c.b[2];
  return c.W * Math.pow(phi, c.eta) * Math.exp(-c.xi * d * d) * Math.pow(Tu / 298, alpha) * Math.pow(p / P_ATM, beta);
}

/**
 * Rhodes & Keck, SAE 850047 (1985), Eqs. (22)–(24), indolene (RMFD-303) — a gasoline-like
 * fuel (RON 101.4, MON 88.3): S_uo = 30.5 − 54.9(φ − 1.21)² cm/s, α = 2.4 − 0.271 φ^3.51,
 * β = −0.357 + 0.14 φ^2.77; T0 = 298 K, p0 = 1 atm; measured φ 0.7–1.6, 0.4–12 atm, 350–550 K.
 */
export function rhodesKeck1985Indolene(phi: number, Tu: number, p: number): number {
  if (!(phi > 0)) return 0;
  const d = phi - 1.21;
  const s0 = 0.305 - 0.549 * d * d;
  if (!(s0 > 0)) return 0;
  const alpha = 2.4 - 0.271 * Math.pow(phi, 3.51);
  const beta = -0.357 + 0.14 * Math.pow(phi, 2.77);
  return s0 * Math.pow(Tu / 298, alpha) * Math.pow(p / P_ATM, beta);
}

/**
 * Residual/EGR dilution factor S_L(f)/S_L(0) = 1 − 2.06 f^0.773 (Rhodes & Keck 1985, Eq. 25,
 * a = 2.06, b = 0.773; verified on the SAE 850047 scan, p. 10). f is the VOLUME (mole) fraction of
 * their simulated residual, 20 % CO2 + 80 % N2 by volume, measured for f = 0–0.3 with RMFD-303
 * (for that diluent "the fraction by volume is 3 % lower than the fraction by mass", p. 10).
 * Clipped at 0 (f ≥ 0.393).
 */
export function rhodesKeckDilutionFactor(x: number): number {
  if (!(x > 0)) return 1;
  const f = 1 - 2.06 * Math.pow(x, 0.773);
  return f > 0 ? f : 0;
}

/**
 * Metghalchi & Keck (1982) dilution factor 1 − 2.1 f, Eq. (24) (diluent MASS fraction f ≤ 0.2 of
 * 85 % N2 / 15 % CO2 by volume, isooctane and indolene).
 */
export function metghalchiKeckDilutionFactor(x: number): number {
  if (!(x > 0)) return 1;
  const f = 1 - 2.1 * x;
  return f > 0 ? f : 0;
}

