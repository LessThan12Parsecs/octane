/** ln S_L from a table with the current weights. */
function tableLnSL(tab: Float64Array): number {
  let acc = 0;
  for (let a = 0; a < 4; a++) {
    const wa = W_PHI[a];
    if (wa === 0) continue;
    const baseA = (bPhi + a) * NT_;
    for (let c = 0; c < 4; c++) {
      const wac = wa * W_T[c];
      if (wac === 0) continue;
      const o = (baseA + bT + c) * NP_ + bP;
      acc += wac * (W_P[0] * tab[o] + W_P[1] * tab[o + 1] + W_P[2] * tab[o + 2] + W_P[3] * tab[o + 3]);
    }
  }
  return acc;
}

