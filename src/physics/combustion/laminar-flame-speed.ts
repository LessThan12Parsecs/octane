/** Laminar flame thickness estimates. */
export interface FlameThickness {
  /** Unburned thermal diffusivity α_u = λ/(ρ c_p), m²/s. */
  alphaU: number;
  /** Diffusive (Zel'dovich) thickness δ_D = α_u/S_L, m. */
  diffusive: number;
  /** Blint (1986) thickness δ_B = 2 δ_D (T_b/T_u)^0.7, m (≈ thermal thickness (T_b−T_u)/max|∇T|). */
  blint: number;
  /** Burned temperature used for Blint, K. */
  Tb: number;
}

const bgScratch: BurnedGasState = { Tb: 0, Mu: 0, Mb: 0, sigma: 0, method: 'table' };

/**
 * Laminar flame thickness of the fresh charge at (φ, Tu [K], p [Pa]) burning at S_L (m/s):
 * diffusive δ_D = α_u/S_L and Blint's δ_B = 2 δ_D (T_b/T_u)^0.7 (Blint 1986; Vancoillie et al.
 * 2012 Eq. 10). T_b defaults to the burnedGasState estimate; pass Tb (K) from an equilibrium
 * burned state for accuracy. Thicknesses are NaN if SL ≤ 0 (non-propagating mixture).
 */
export function flameThickness(
  fuel: FuelBlend,
  phi: number,
  Tu: number,
  p: number,
  SL: number,
  xDiluent = 0,
  Tb?: number,
  out: FlameThickness = { alphaU: 0, diffusive: 0, blint: 0, Tb: 0 },
): FlameThickness {
  const Xu = unburnedComposition(fuel, phi, xDiluent, scrXu);
  const a = mixThermalDiffusivity(Xu, Tu, p);
  const tb = Tb !== undefined && Tb > 0 ? Tb : burnedGasState(fuel, phi, Tu, p, xDiluent, 'table', bgScratch).Tb;
  const s = SL > 0 ? SL : NaN;
  out.alphaU = a;
  out.diffusive = a / s;
  out.blint = (2 * a / s) * Math.pow(tb / Tu, 0.7);
  out.Tb = tb;
  return out;
}

// =========================================================================================
// Diffusion coefficients and Lewis numbers
// =========================================================================================

const LJ_EPS = Float64Array.from(SPECIES_TRANSPORT, (t) => t.wellDepth);
const LJ_SIGMA = Float64Array.from(SPECIES_TRANSPORT, (t) => t.diameter * 1e-10);
const MASS_MOLECULE = Float64Array.from(MOLAR_MASS, (m) => m / N_AVOGADRO);

/**
 * Binary diffusion coefficient of species i in j at T (K), p (Pa), m²/s — first
 * Chapman–Enskog approximation (Hirschfelder, Curtiss & Bird 1954; the formula Cantera uses —
 * agreement with Cantera 3.2 binary_diff_coeffs ≤ 0.1 %, test file):
 *   D_ij = (3/16) √(2π (k_B T)³/m_ij) / (p π σ_ij² Ω(1,1)*(T/ε_ij)),
 * m_ij = m_i m_j/(m_i + m_j), σ_ij = (σ_i + σ_j)/2, ε_ij = √(ε_i ε_j) (Lennard-Jones mixing
 * rules), Ω(1,1)* from Neufeld et al. (1972). Polar corrections are omitted (only H2O is
 * polar in our fresh charges; its effect on fuel/O2 mixture diffusivities is < 1 %).
 */
export function binaryDiffusionCoefficient(i: number, j: number, T: number, p: number): number {
  const mij = (MASS_MOLECULE[i] * MASS_MOLECULE[j]) / (MASS_MOLECULE[i] + MASS_MOLECULE[j]);
  const sij = 0.5 * (LJ_SIGMA[i] + LJ_SIGMA[j]);
  const eij = Math.sqrt(LJ_EPS[i] * LJ_EPS[j]);
  const kT = K_BOLTZMANN * T;
  return ((3 / 16) * Math.sqrt((2 * Math.PI * kT * kT * kT) / mij)) / (p * Math.PI * sij * sij * omega11LJ(T / eij));
}

/**
 * Mixture-averaged diffusion coefficient of species k, m²/s:
 * D_k,m = (1 − Y_k) / Σ_{j≠k} X_j/D_kj (Kee, Coltrin & Glarborg 2003; Cantera's
 * `mix_diff_coeffs`). X mole fractions (normalised).
 */
export function mixtureDiffusionCoefficient(X: Float64Array, k: number, T: number, p: number): number {
  let s = 0;
  let m = 0;
  for (let j = 0; j < NS; j++) {
    m += X[j] * MOLAR_MASS[j];
    if (j === k || !(X[j] > 0)) continue;
    s += X[j] / binaryDiffusionCoefficient(k, j, T, p);
  }
  const Yk = (X[k] * MOLAR_MASS[k]) / m;
  return (1 - Yk) / s;
}

/** Lewis numbers of the fresh charge. */
export interface LewisNumbers {
  /** Fuel Lewis number α_u/D_F,m (blends: mole-fraction-weighted mean D_F). */
  fuel: number;
  /** Oxygen Lewis number α_u/D_O2,m. */
  oxygen: number;
  /** Lewis number of the deficient reactant (fuel if φ ≤ 1, O2 otherwise). */
  deficient: number;
  /** Unburned thermal diffusivity, m²/s. */
  alphaU: number;
}

/**
 * Lewis numbers of fuel and O2 in the fresh charge at Tu (K), p (Pa) (unburned-gas properties;
 * Le is nearly temperature-independent). Not a hot path (~a few µs).
 */
export function lewisNumbers(
  fuel: FuelBlend,
  phi: number,
  Tu: number,
  p: number,
  xDiluent = 0,
  out: LewisNumbers = { fuel: 0, oxygen: 0, deficient: 0, alphaU: 0 },
): LewisNumbers {
  const Xu = unburnedComposition(fuel, phi, xDiluent, scrXu);
  const a = mixThermalDiffusivity(Xu, Tu, p);
  let dF = 0;
  let ys = 0;
  for (let f = 0; f < NF; f++) {
    const k = FUEL_IDX[f];
    const y = fuel.X[k];
    if (!(y > 0)) continue;
    dF += y * mixtureDiffusionCoefficient(Xu, k, Tu, p);
    ys += y;
  }
  dF /= ys;
  const dO = mixtureDiffusionCoefficient(Xu, SP.O2, Tu, p);
  out.alphaU = a;
  out.fuel = a / dF;
  out.oxygen = a / dO;
  out.deficient = phi <= 1 ? out.fuel : out.oxygen;
  return out;
}

