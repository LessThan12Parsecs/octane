/** Minimal HP-equilibrium interface (satisfied by equilibrium/EquilibriumSolver). */
export interface HPEquilibriumSolver {
  solveHP(b: Float64Array, H: number, p: number, Tguess: number): { T: number; nTotal: number; converged: boolean };
}

/**
 * How burnedGasState obtains T_b: 'table' — HP-equilibrium T_ad interpolated from the generated
 * tables (default; product moles from complete combustion); 'complete-combustion' — exact
 * enthalpy balance without dissociation (upper bound); or an HP equilibrium solver.
 */
export type BurnedGasMethod = 'table' | 'complete-combustion' | HPEquilibriumSolver;

/** Burned (adiabatic, constant-pressure) state. */
export interface BurnedGasState {
  /** Adiabatic flame temperature T_b, K. */
  Tb: number;
  /** Unburned and burned molar masses, kg/mol. */
  Mu: number;
  Mb: number;
  /** Density ratio σ = ρ_u/ρ_b. */
  sigma: number;
  /** Method actually used. */
  method: 'table' | 'complete-combustion' | 'solver';
}

/** σ = ρ_u/ρ_b = (M_u T_b)/(M_b T_u) at equal pressure (ideal gas), dimensionless. */
export function expansionRatio(Mu: number, Tu: number, Mb: number, Tb: number): number {
  return (Mu * Tb) / (Mb * Tu);
}

/**
 * Adiabatic constant-pressure burned state of the fresh charge (fuel, φ, Tu, p, x).
 *  • 'table' (default): T_b = HP-equilibrium T_ad from the tables (≤ 0.3 % from Cantera
 *    equilibrium with the same thermo at the nodes); burned moles from complete combustion
 *    (dissociation adds ≲ 2 % moles near φ = 1 at high T_b, so σ is low by that much).
 *  • 'complete-combustion': CO2, H2O, O2 lean / water-gas shift at 1740 K rich
 *    (thermo/fuels completeCombustionMoles) with the exact enthalpy balance H_b(T_b) = H_u(T_u);
 *    no dissociation → T_b is an upper bound (+0.3 … +12 % vs equilibrium).
 *  • an HP solver (e.g. equilibrium/EquilibriumSolver): full chemical equilibrium.
 * Not a hot path.
 */
export function burnedGasState(
  fuel: FuelBlend,
  phi: number,
  Tu: number,
  p: number,
  xDiluent = 0,
  method: BurnedGasMethod = 'table',
  out: BurnedGasState = { Tb: 0, Mu: 0, Mb: 0, sigma: 0, method: 'table' },
): BurnedGasState {
  const x = xDiluent > 0 ? (xDiluent < 0.95 ? xDiluent : 0.95) : 0;
  const Xu = unburnedComposition(fuel, phi, x, scrXu);
  const Mu = molarMass(Xu);
  out.Mu = Mu;
  if (typeof method === 'object') {
    const b = elementMoles(Xu, scrB);
    const r = method.solveHP(b, mixHMolar(Xu, Tu), p, 2200);
    if (r.converged && r.T > 0 && r.nTotal > 0) {
      out.Tb = r.T;
      out.Mb = Mu / r.nTotal;
      out.sigma = (r.nTotal * r.T) / Tu;
      out.method = 'solver';
      return out;
    }
  }
  completeCombustionMoles(Xu, scrNb);
  let nb = 0;
  for (let k = 0; k < NS; k++) nb += scrNb[k];
  let Tb = NaN;
  if (method === 'table') {
    setTableWeights(phi, Tu, p);
    let qs = 0;
    let i0 = 0;
    let i1 = 0;
    let i2 = 0;
    for (let f = 0; f < NF; f++) {
      const y = fuel.X[FUEL_IDX[f]];
      if (!(y > 0)) continue;
      const tad = TAD_BY_FUEL[f];
      if (tad === null) {
        qs = 0;
        break;
      }
      const q = y * FUEL_LHV_MOLAR[f];
      tableInvTad(tad);
      qs += q;
      i0 += q * INV_TAD[0];
      i1 += q * INV_TAD[1];
      i2 += q * INV_TAD[2];
    }
    if (qs > 0) {
      Tb = 1 / quadInX(x, i0 / qs, i1 / qs, i2 / qs);
      out.method = 'table';
    }
  }
  if (!(Tb > Tu)) {
    Tb = temperatureFromHMolar(scrNb, mixHMolar(Xu, Tu), 2200);
    out.method = 'complete-combustion';
  }
  out.Tb = Tb;
  out.Mb = Mu / nb;
  out.sigma = (nb * Tb) / Tu;
  return out;
}

