const scrXu = new Float64Array(NS);
const scrN = new Float64Array(NS);
const scrNb = new Float64Array(NS);
const scrB = new Float64Array(NE);

/**
 * Fresh-charge mole fractions (dry air + fuel vapour at φ + diluent of MASS fraction x) into
 * `out`. The diluent is the complete-combustion product of the fuel–air mixture itself
 * (a residual-gas surrogate). Allocation-free.
 */
export function unburnedComposition(fuel: FuelBlend, phi: number, xDiluent: number, out: Float64Array): Float64Array {
  const nuMix = stoichO2PerMolFuel(fuel);
  let ysum = 0;
  for (let f = 0; f < NF; f++) ysum += fuel.X[FUEL_IDX[f]];
  const nFuel = (phi * AIR_X[SP.O2]) / nuMix; // mol fuel per mol air
  for (let k = 0; k < NS; k++) scrN[k] = AIR_X[k] + (nFuel * fuel.X[k]) / ysum;
  out.fill(0);
  const x = xDiluent > 0 ? (xDiluent < 0.95 ? xDiluent : 0.95) : 0;
  if (x > 0) {
    // Diluent mass = x/(1−x) × fresh fuel–air mass; the products of scrN have the same mass as
    // scrN itself (element conservation), so the product moles are simply scaled.
    completeCombustionMoles(scrN, scrNb);
    const scale = x / (1 - x);
    for (let k = 0; k < NS; k++) out[k] = scrN[k] + scale * scrNb[k];
  } else {
    for (let k = 0; k < NS; k++) out[k] = scrN[k];
  }
  let s = 0;
  for (let k = 0; k < NS; k++) s += out[k];
  for (let k = 0; k < NS; k++) out[k] /= s;
  return out;
}

/** Mixture molar mass of a mole-fraction vector, kg/mol. */
function molarMass(X: Float64Array): number {
  let m = 0;
  let s = 0;
  for (let k = 0; k < NS; k++) {
    m += X[k] * MOLAR_MASS[k];
    s += X[k];
  }
  return m / s;
}

