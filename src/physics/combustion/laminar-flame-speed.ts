/** Precomputed per-blend data: ln S_L at every node for the three TABLE_XDIL, and 298 K limits. */
interface BlendTables {
  /** Fuel-vapour mole fractions (FUEL_SPECIES order) the tables were built for (cache key). */
  y: Float64Array;
  /** ln(S_L/(m/s)) at node n and diluent fraction x_j: index 3n + j. */
  lnS: Float64Array;
  lean298: number;
  rich298: number;
  k: number;
  /** φ for which `tp` holds the table contracted over the φ axis (NaN: none). */
  phi: number;
  /** ln S_L on the (Tu, p) nodes at `phi`, index 3 (iT·NP + ip) + j. */
  tp: Float64Array;
}

/**
 * Per-blend tables, cached by fuel COMPOSITION (not by object identity): every lookup compares
 * the NF fuel mole fractions of `fuel.X` with the cached entry (≈ 5 compares, no allocation), so
 * mutating a FuelBlend.X in place, or passing a fresh FuelBlend with the same composition on
 * every call (e.g. fuelFromSelection inside a loop), is safe and does not rebuild the tables.
 * The last BLEND_CACHE_SIZE compositions are kept (most recent first).
 */
const BLEND_CACHE_SIZE = 16;
const blendCache: BlendTables[] = [];

function sameComposition(y: Float64Array, X: Float64Array): boolean {
  for (let f = 0; f < NF; f++) if (y[f] !== X[FUEL_IDX[f]]) return false;
  return true;
}

/** Per-blend tables (composition-keyed, most-recently-used first). */
function blendTables(fuel: FuelBlend): BlendTables {
  const X = fuel.X;
  const n = blendCache.length;
  if (n > 0 && sameComposition(blendCache[0].y, X)) return blendCache[0];
  for (let i = 1; i < n; i++) {
    const c = blendCache[i];
    if (sameComposition(c.y, X)) {
      for (let j = i; j > 0; j--) blendCache[j] = blendCache[j - 1];
      blendCache[0] = c;
      return c;
    }
  }
  const c = buildBlendTables(fuel);
  if (n >= BLEND_CACHE_SIZE) blendCache.pop();
  blendCache.unshift(c);
  return c;
}

/**
 * Drop all cached per-blend tables. Never required for correctness (the cache is keyed by
 * composition); kept for memory control and API compatibility.
 */
export function clearFlameSpeedCache(_fuel?: FuelBlend): void {
  blendCache.length = 0;
}

/**
 * Build the per-blend node table: at every (φ, Tu, p) node, S_L,blend = Σ τ_k S_L,k (energy
 * fractions τ; pure-fuel values from the oracle tables or, for C3H8 / C2H5OH, the closed-form
 * correlations evaluated at the node), and the thermal-theory dilution factor
 * ln F_j = −Ē_a,j/(2R) (1/T̄_ad(x_j) − 1/T̄_ad(0)) with τ-weighted E_a(φ, p, x_j) and ln T_ad. Without
 * T_ad tables the Rhodes–Keck factor is used. Not a hot path (≈ 0.1 ms, once per blend).
 */
function buildBlendTables(fuel: FuelBlend): BlendTables {
  const nNode = AX_PHI.n * NT_ * NP_;
  const lnS = new Float64Array(3 * nNode);
  const tau = new Float64Array(NF);
  let qs = 0;
  for (let f = 0; f < NF; f++) {
    const y = fuel.X[FUEL_IDX[f]];
    if (y > 0) {
      tau[f] = y * FUEL_LHV_MOLAR[f];
      qs += tau[f];
    }
  }
  baseLimits(fuel);
  const y = new Float64Array(NF);
  for (let f = 0; f < NF; f++) y[f] = fuel.X[FUEL_IDX[f]];
  const out: BlendTables = { y, lnS, lean298: LIM[0], rich298: LIM[1], k: LIM[2], phi: NaN, tp: new Float64Array(3 * NT_ * NP_) };
  if (!(qs > 0)) {
    lnS.fill(-Infinity);
    return out;
  }
  for (let f = 0; f < NF; f++) tau[f] /= qs;
  const rk1 = Math.log(Math.max(rhodesKeckDilutionFactor(TABLE_XDIL[1]), 1e-300));
  const rk2 = Math.log(Math.max(rhodesKeckDilutionFactor(TABLE_XDIL[2]), 1e-300));
  for (let i = 0; i < AX_PHI.n; i++) {
    const phi = TABLE_PHI[i];
    for (let j = 0; j < NT_; j++) {
      const Tu = TABLE_TU[j];
      for (let k = 0; k < NP_; k++) {
        const p = TABLE_P[k];
        const n = (i * NT_ + j) * NP_ + k;
        let sBlend = 0;
        let l0 = 0;
        let l1 = 0;
        let l2 = 0;
        let ea1 = 0;
        let ea2 = 0;
        let thermal = true;
        for (let f = 0; f < NF; f++) {
          const t = tau[f];
          if (!(t > 0)) continue;
          const tab = TABLE_BY_FUEL[f];
          const sf = tab !== null ? Math.exp(tab[n]) : pureClosedForm(f, phi, Tu, p);
          sBlend += t * (sf > 1e-8 ? sf : 1e-8);
          const tad = TAD_BY_FUEL[f];
          if (tad === null) {
            thermal = false;
          } else {
            l0 += t * tad[3 * n];
            l1 += t * tad[3 * n + 1];
            l2 += t * tad[3 * n + 2];
          }
          ea1 += t * activationEnergy(f, phi, p, 0);
          ea2 += t * activationEnergy(f, phi, p, 1);
        }
        const L = Math.log(sBlend);
        lnS[3 * n] = L;
        if (thermal) {
          const i0 = Math.exp(-l0);
          lnS[3 * n + 1] = L - (ea1 / (2 * R_UNIVERSAL)) * (Math.exp(-l1) - i0);
          lnS[3 * n + 2] = L - (ea2 / (2 * R_UNIVERSAL)) * (Math.exp(-l2) - i0);
        } else {
          lnS[3 * n + 1] = L + rk1;
          lnS[3 * n + 2] = L + rk2;
        }
      }
    }
  }
  return out;
}

/**
 * Unstretched laminar burning velocity S_L (m/s) of a fuel blend in air at equivalence ratio
 * φ, unburned temperature Tu (K), pressure p (Pa), with a residual/EGR diluent MASS fraction
 * xDiluent (0..1; complete-combustion products of the same mixture). Valid (oracle-backed) for
 * Tu 300–900 K, p 1–60 bar, φ 0.5–1.6, x ≤ 0.3; smooth extrapolation to Tu 950 K, p 0.5–100 bar,
 * φ 0.4–1.8. Never negative or NaN; 0 outside the flammability limits. Hot path:
 * allocation-free, ~0.1–0.2 µs.
 *
 * Dilution (thermal theory, Zel'dovich–Frank-Kamenetskii): S_L(x)/S_L(0) =
 * exp[−E_a/(2R) (1/T_ad(x) − 1/T_ad(0))], with the equilibrium T_ad of the diluted and undiluted
 * charge from the tables and an effective E_a(φ, p, x) from paired diluted/undiluted
 * detailed-chemistry flames (ACTIVATION_ENERGY_TABLE). Unlike a fixed factor (Rhodes & Keck 1985,
 * rhodesKeckDilutionFactor) it captures the higher dilution tolerance of hot, high-T_ad and
 * off-stoichiometric mixtures (e.g. iso-octane at 700 K / 20 bar, x = 0.3: Cantera 0.29,
 * Rhodes–Keck 0.19).
 */
export function laminarFlameSpeed(fuel: FuelBlend, phi: number, Tu: number, p: number, xDiluent: number): number {
  if (!(phi > 0 && Tu > 0 && p > 0)) return 0;
  const x = xDiluent > 0 ? (xDiluent < 0.95 ? xDiluent : 0.95) : 0;
  const c = blendTables(fuel);
  adjustLimits(c.lean298, c.rich298, c.k, Tu, x);
  const g = smoothstep((phi - LIM[0]) / (LIMIT_BAND * LIM[0])) * smoothstep((LIM[1] - phi) / (LIMIT_BAND * LIM[1]));
  if (!(g > 0)) return 0;
  // φ is constant over an engine cycle: contract the φ axis once per φ (192 MACs), then each
  // call costs two 1-D weight sets and a 16-node (×3) sum.
  if (phi !== c.phi) contractPhi(c, phi);
  bT = hermiteWeights(AX_LNT, Math.log(Tu), W_T);
  bP = hermiteWeights(AX_LNP, Math.log(p), W_P);
  const tp = c.tp;
  let a0 = 0;
  let a1 = 0;
  let a2 = 0;
  for (let cc = 0; cc < 4; cc++) {
    const wc = W_T[cc];
    if (wc === 0) continue;
    let o = 3 * ((bT + cc) * NP_ + bP);
    if (x > 0) {
      for (let d = 0; d < 4; d++, o += 3) {
        const w = wc * W_P[d];
        a0 += w * tp[o];
        a1 += w * tp[o + 1];
        a2 += w * tp[o + 2];
      }
    } else {
      a0 += wc * (W_P[0] * tp[o] + W_P[1] * tp[o + 3] + W_P[2] * tp[o + 6] + W_P[3] * tp[o + 9]);
    }
  }
  const s = Math.exp(x > 0 ? quadInX(x, a0, a1, a2) : a0) * g;
  return s > 0 && s < Infinity ? s : 0;
}

/** Contract the blend's node table over the φ axis at `phi` into c.tp. */
function contractPhi(c: BlendTables, phi: number): void {
  const b = hermiteWeights(AX_PHI, phi, W_PHI);
  const tp = c.tp;
  const lnS = c.lnS;
  const m = 3 * NT_ * NP_;
  tp.fill(0);
  for (let a = 0; a < 4; a++) {
    const w = W_PHI[a];
    if (w === 0) continue;
    const o = (b + a) * m;
    for (let q = 0; q < m; q++) tp[q] += w * lnS[o + q];
  }
  c.phi = phi;
}

/** Selectable burning-velocity models (for comparison with the default). */
export type FlameSpeedModel = 'default' | 'metghalchi-keck-1982' | 'gulder-1984' | 'amirante-2017' | 'rhodes-keck-1985';

/**
 * Burning velocity (m/s) of a PURE fuel species from a named model, undiluted, without the
 * flammability cut-off; NaN if the model has no constants for that fuel. Not a hot path.
 * 'metghalchi-keck-1982': IC8H18, C3H8; 'gulder-1984': CH4, C3H8, IC8H18, C2H5OH;
 * 'amirante-2017': CH4, C3H8; 'rhodes-keck-1985': indolene constants (used for any fuel).
 */
export function laminarFlameSpeedModel(
  model: FlameSpeedModel,
  species: (typeof FUEL_SPECIES)[number],
  phi: number,
  Tu: number,
  p: number,
): number {
  switch (model) {
    case 'default': {
      const f = FUEL_SPECIES.indexOf(species);
      setTableWeights(phi, Tu, p);
      return pureSL(f, phi, Tu, p);
    }
    case 'metghalchi-keck-1982':
      if (species === 'IC8H18') return metghalchiKeck1982(METGHALCHI_KECK_1982.isooctane, phi, Tu, p);
      if (species === 'C3H8') return metghalchiKeck1982(METGHALCHI_KECK_1982.propane, phi, Tu, p);
      return NaN;
    case 'gulder-1984':
      if (species === 'NC7H16') return NaN;
      return gulder1984(GULDER_1984[species], phi, Tu, p);
    case 'amirante-2017':
      if (species === 'CH4' || species === 'C3H8') return amirante2017(AMIRANTE_2017[species], phi, Tu, p);
      return NaN;
    case 'rhodes-keck-1985':
      return rhodesKeck1985Indolene(phi, Tu, p);
  }
}

